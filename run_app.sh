#!/bin/bash
# -----------------------------------------------------------------------------
# Universal Package Manager App Launcher Script (AppImage Wrapper Style)
# Назначение: Запускает приложение в изолированной среде, минимизируя риски.
# Требования: Python 3, PySide6, зависимости для pacman/flatpak.
# -----------------------------------------------------------------------------

echo "==============================================="
echo "🚀 Universal Package Manager v0.1 (Build Test)"
echo "Обнаружен запуск из скрипта оболочки."
echo "==============================================="

# --- Меры безопасности и изоляция ---
# 1. Проверка прав: Предупреждаем пользователя о необходимости ручного ввода sudo, когда это потребуется для установки.
if [[ $EUID -eq 0 ]]; then
    echo "⚠️ ВНИМАНИЕ: Скрипт запущен с root-правами ($$). Рекомендуется запуск от обычного пользователя."
fi

# 2. Установка окружения (если не задано)
# Здесь в реальном AppImage было бы копирование всего необходимого окружения.
# Для простоты разработки, мы полагаемся на окружение пользователя.

PYTHON_EXECUTABLE="/usr/bin/python3" # Предполагаемый путь к Python 3
MAIN_GUI="gui/main_window.py"

if [ ! -f "$MAIN_GUI" ]; then
    echo "❌ ОШИБКА: Не найден основной файл GUI '$MAIN_GUI'. Проверьте структуру проекта."
    exit 1
fi

echo "▶️ Запуск графического интерфейса..."

# Запуск приложения через PySide6. QApplication должен быть запущен в foreground.
# Мы передаем аргументы, чтобы убедиться, что все необходимые модули доступны.
if ! "$PYTHON_EXECUTABLE" "$MAIN_GUI"; then
    echo "❌ КРИТИЧЕСКАЯ ОШИБКА: Не удалось запустить GUI."
    echo "Проверьте установку PySide6 и зависимости Pacman/Flatpak в вашей системе."
    exit 1
fi

echo -e "\n==============================================="
echo "👋 Приложение закрыто. Спасибо за использование UPM."